function teamSelectionWeight(card: WordCard): 0 | 1 | 2 {
  if (teamEasiestWords[card.difficulty].includes(card.word)) return 0
  if (teamHardestWords[card.difficulty].includes(card.word)) return 2
  return 1
}

export const WORD_BANK: WordCard[] = [...coreWords, ...extraWords].map((card) => ({
  ...card,
  teamSelectionWeight: teamSelectionWeight(card),
}))

export function getWord(id: string | null): WordCard | undefined {
  return WORD_BANK.find((card) => card.id === id)
}
